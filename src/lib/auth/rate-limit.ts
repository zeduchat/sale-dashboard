// In-memory sliding window. Good enough for a single instance; swap for Redis/Postgres if the app scales out.
const hits = new Map<string, number[]>();

/** Returns true when the call is allowed, false when `key` exceeded `max` hits within `windowMs`. */
export function rateLimit(key: string, max: number, windowMs: number) {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= max) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) for (const [k, v] of hits) if (!v.some((t) => now - t < windowMs)) hits.delete(k);
  return true;
}
